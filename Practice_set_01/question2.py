# Q2. Swap the value of two variable using both the traditional method and python's tuple unpacking.
# Traditional method
a = 10
b = 20
temp = a
a = b
b = temp
print("After swapping using traditional method:")
print("a =", a)
print("b =", b)
# Python's tuple unpaking 
x = 30
y = 40
x, y = y, x
print("After swapping using tuple unpacking:")
print("x =", x)
print("y =", y)

